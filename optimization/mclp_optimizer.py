"""
UrbanFlow AI - Maximal Covering Location Problem (MCLP) Optimizer
Formulated as an exact Mixed-Integer Linear Program (MILP) using Google OR-Tools (with PuLP fallback).

Implements Part B & Part C:
    Maximize sum_i (demand_i * pop_i * (1 + DTII_i) * y_i)
    subject to:
        sum_{j in N_i} x_j >= y_i         (coverage linkage)
        sum_j x_j <= K                   (maximum new facilities)
        sum_j (cost_j * x_j) <= Budget   (optional budget limit)
        x_{j1} + x_{j2} <= 1             (minimum separation constraint for close pairs)
        x_j, y_i in {0, 1}

DISCLAIMER:
Candidate stops evaluated are potential planning recommendations for feeder connectivity
improvements generated by the UrbanFlow AI optimization model. They are not approved bus stops
or operational BEST facilities.
"""

import time
from typing import Dict, Any, List, Optional
import numpy as np
from ortools.linear_solver import pywraplp
import pulp

from optimization.fitness_function import MultiObjectiveFitnessEvaluator, FITNESS_DISCLAIMER
from utils.logger import logger


class MCLPOptimizer:
    """Exact MILP solver for the Maximal Covering Location Problem considering underserved areas."""

    DISCLAIMER = FITNESS_DISCLAIMER

    def __init__(self, evaluator: MultiObjectiveFitnessEvaluator):
        self.evaluator = evaluator
        self.coverage_matrix = evaluator.coverage_matrix # (I x J) boolean
        self.populations = evaluator.populations         # (I)
        self.num_demand_units = len(self.populations)
        self.num_candidates = len(evaluator.candidates_metric)

        # Precompute candidate coordinates in metric CRS
        self.cand_coords = np.column_stack([
            evaluator.candidates_metric.geometry.x.values,
            evaluator.candidates_metric.geometry.y.values
        ])
        self.costs = evaluator.costs

    def optimize(
        self,
        budget_stops: int = 15,
        max_budget_lakhs: Optional[float] = None,
        min_separation_m: float = 300.0,
        time_limit_sec: int = 30
    ) -> Dict[str, Any]:
        """
        Solves the MCLP to global mathematical optimality.
        """
        start_time = time.time()
        logger.info(
            f"Formulating MCLP MILP (demand units: {self.num_demand_units}, "
            f"candidates: {self.num_candidates}, K: {budget_stops})..."
        )

        # Weights: demand_i * pop_i * (1 + DTII_i)
        w_dtii = self.evaluator.base_dtii
        w_dem = self.evaluator.base_demand
        weights = self.populations * (1.0 + w_dtii) * (w_dem / 100.0)

        # 1. Try Google OR-Tools
        solver = pywraplp.Solver.CreateSolver("SCIP")
        if not solver:
            solver = pywraplp.Solver.CreateSolver("CBC")

        if solver:
            return self._solve_ortools(
                solver=solver,
                budget_stops=budget_stops,
                weights=weights,
                max_budget_lakhs=max_budget_lakhs,
                min_separation_m=min_separation_m,
                time_limit_sec=time_limit_sec,
                start_time=start_time
            )
        else:
            logger.info("OR-Tools solver not available; falling back to PuLP MILP solver...")
            return self._solve_pulp(
                budget_stops=budget_stops,
                weights=weights,
                max_budget_lakhs=max_budget_lakhs,
                min_separation_m=min_separation_m,
                time_limit_sec=time_limit_sec,
                start_time=start_time
            )

    def _solve_ortools(
        self,
        solver: Any,
        budget_stops: int,
        weights: np.ndarray,
        max_budget_lakhs: Optional[float],
        min_separation_m: float,
        time_limit_sec: int,
        start_time: float
    ) -> Dict[str, Any]:
        """Solves MCLP using Google OR-Tools pywraplp."""
        solver.SetTimeLimit(time_limit_sec * 1000)

        # Decision variables
        x = [solver.BoolVar(f"x_{j}") for j in range(self.num_candidates)]
        y = [solver.BoolVar(f"y_{i}") for i in range(self.num_demand_units)]

        # Objective: Maximize population-weighted demand coverage
        objective = solver.Objective()
        for i in range(self.num_demand_units):
            objective.SetCoefficient(y[i], float(weights[i]))
        objective.SetMaximization()

        # Constraint 1: Max facilities K
        budget_constraint = solver.Constraint(0, budget_stops)
        for j in range(self.num_candidates):
            budget_constraint.SetCoefficient(x[j], 1.0)

        # Constraint 2: Optional capital budget limit (in Lakhs INR)
        if max_budget_lakhs is not None and max_budget_lakhs > 0:
            cost_constraint = solver.Constraint(0, float(max_budget_lakhs))
            for j in range(self.num_candidates):
                cost_constraint.SetCoefficient(x[j], float(self.costs[j]))

        # Constraint 3: Coverage linkage sum_{j in N_i} x_j >= y_i
        for i in range(self.num_demand_units):
            covering_candidates = [j for j in range(self.num_candidates) if self.coverage_matrix[i, j]]
            if covering_candidates:
                cov_constraint = solver.Constraint(0, solver.infinity())
                for j in covering_candidates:
                    cov_constraint.SetCoefficient(x[j], 1.0)
                cov_constraint.SetCoefficient(y[i], -1.0)
            else:
                y[i].SetBounds(0, 0)

        # Constraint 4: Mutual minimum separation between candidates
        if min_separation_m > 0 and self.num_candidates <= 100:
            for j1 in range(self.num_candidates):
                for j2 in range(j1 + 1, self.num_candidates):
                    dist_j = float(np.hypot(
                        self.cand_coords[j1, 0] - self.cand_coords[j2, 0],
                        self.cand_coords[j1, 1] - self.cand_coords[j2, 1]
                    ))
                    if dist_j < min_separation_m:
                        sep_constraint = solver.Constraint(0, 1.0)
                        sep_constraint.SetCoefficient(x[j1], 1.0)
                        sep_constraint.SetCoefficient(x[j2], 1.0)

        status = solver.Solve()
        elapsed = time.time() - start_time

        selected_mask = np.array([x[j].solution_value() > 0.5 for j in range(self.num_candidates)], dtype=bool)
        selected_indices = np.where(selected_mask)[0].tolist()

        final_fitness, metrics = self.evaluator.evaluate(selected_mask)
        selected_ids = self.evaluator.candidates_metric.iloc[selected_indices]["candidate_id"].tolist()
        status_str = "OPTIMAL" if status == pywraplp.Solver.OPTIMAL else "FEASIBLE"

        metrics.update({
            "algorithm": "MCLP (OR-Tools Exact MILP)",
            "execution_time_sec": round(elapsed, 4),
            "solver_status": status_str,
            "selected_indices": selected_indices,
            "selected_stop_ids": selected_ids,
            "convergence_history": [metrics["fitness"]],
            "disclaimer": FITNESS_DISCLAIMER
        })
        logger.info(
            f"MCLP solved in {elapsed:.3f}s with status '{status_str}'. "
            f"Covered Pop: {metrics['population_covered']:,}, Additional: {metrics['additional_population_benefiting']:,}"
        )
        return metrics

    def _solve_pulp(
        self,
        budget_stops: int,
        weights: np.ndarray,
        max_budget_lakhs: Optional[float],
        min_separation_m: float,
        time_limit_sec: int,
        start_time: float
    ) -> Dict[str, Any]:
        """Fallback solver using PuLP."""
        prob = pulp.LpProblem("MCLP_Transit", pulp.LpMaximize)

        x = [pulp.LpVariable(f"x_{j}", cat=pulp.LpBinary) for j in range(self.num_candidates)]
        y = [pulp.LpVariable(f"y_{i}", cat=pulp.LpBinary) for i in range(self.num_demand_units)]

        # Objective
        prob += pulp.lpSum([weights[i] * y[i] for i in range(self.num_demand_units)])

        # Facility limit
        prob += pulp.lpSum(x) <= budget_stops

        # Budget limit
        if max_budget_lakhs is not None and max_budget_lakhs > 0:
            prob += pulp.lpSum([self.costs[j] * x[j] for j in range(self.num_candidates)]) <= max_budget_lakhs

        # Coverage constraints
        for i in range(self.num_demand_units):
            covering = [x[j] for j in range(self.num_candidates) if self.coverage_matrix[i, j]]
            if covering:
                prob += pulp.lpSum(covering) >= y[i]
            else:
                prob += y[i] == 0

        solver = pulp.PULP_CBC_CMD(timeLimit=time_limit_sec, msg=False)
        prob.solve(solver)
        elapsed = time.time() - start_time

        selected_mask = np.array([pulp.value(x[j]) > 0.5 for j in range(self.num_candidates)], dtype=bool)
        selected_indices = np.where(selected_mask)[0].tolist()

        final_fitness, metrics = self.evaluator.evaluate(selected_mask)
        selected_ids = self.evaluator.candidates_metric.iloc[selected_indices]["candidate_id"].tolist()

        metrics.update({
            "algorithm": "MCLP (PuLP Exact MILP)",
            "execution_time_sec": round(elapsed, 4),
            "solver_status": pulp.LpStatus[prob.status],
            "selected_indices": selected_indices,
            "selected_stop_ids": selected_ids,
            "convergence_history": [metrics["fitness"]],
            "disclaimer": FITNESS_DISCLAIMER
        })
        return metrics
