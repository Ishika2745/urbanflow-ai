"""
UrbanFlow AI - Discrete Particle Swarm Optimization (D-PSO)
Rank-Key Discrete PSO with Spatial Separation Constraint Repair for Public Transit Facility Location.

Problem Formulation:
- Discrete candidate facility selection (choose K stops from M mapped infrastructure candidates).
- Continuous Priority Vector (Random Keys): Particle position X_i in R^M represents candidate priority.
- Mapping Function: Decodes continuous priorities into K discrete candidates by selecting top-ranked
  candidates while enforcing hard spatial separation constraints (min_separation_m) and zero duplicates.
- Dynamic Inertia Weight Damping: w(t) decreases linearly from w_max to w_min over iterations.

DISCLAIMER:
Candidate stops evaluated are potential planning recommendations for feeder connectivity
improvements generated by the UrbanFlow AI optimization model. They are not approved bus stops
or operational BEST facilities.
"""

import time
from typing import Dict, Any, List, Tuple, Optional, Set
import numpy as np

from optimization.fitness_function import MultiObjectiveFitnessEvaluator, FITNESS_DISCLAIMER
from utils.logger import logger


class ParticleSwarmOptimizer:
    """
    Rank-Key Discrete Particle Swarm Optimizer (RK-DPSO) for equity-aware transit facility location.
    Enforces exact K-stop cardinality and hard spatial separation rules.
    """

    DISCLAIMER = FITNESS_DISCLAIMER

    def __init__(
        self,
        evaluator: MultiObjectiveFitnessEvaluator,
        num_particles: int = 35,
        iterations: int = 30,
        w_max: float = 0.90,       # Initial inertia weight
        w_min: float = 0.40,       # Final inertia weight
        c1: float = 1.60,          # Cognitive acceleration coefficient
        c2: float = 1.60,          # Social acceleration coefficient
        v_max: float = 4.0,        # Maximum velocity clamp
        min_separation_m: float = 300.0,
        random_seed: Optional[int] = 42
    ):
        self.evaluator = evaluator
        self.num_candidates = len(evaluator.candidates_metric)
        self.num_particles = max(10, num_particles)
        self.iterations = max(5, iterations)
        self.w_max = w_max
        self.w_min = w_min
        self.c1 = c1
        self.c2 = c2
        self.v_max = v_max
        self.min_separation_m = min_separation_m
        self.seed = random_seed

        # Precompute candidate-to-candidate metric distance matrix
        cand_geoms = self.evaluator.candidates_metric.geometry
        coords = np.column_stack([cand_geoms.x.values, cand_geoms.y.values])
        self.cand_dist_matrix = np.linalg.norm(coords[:, None, :] - coords[None, :, :], axis=-1)

    def decode_particle_to_selection(self, position: np.ndarray, budget: int) -> List[int]:
        """
        Maps continuous particle position vector (priorities) to exactly 'budget' unique,
        spatially feasible candidate indices.

        Sorting candidate indices by descending priority, greedily admits candidates
        that satisfy the mutual separation threshold.
        """
        sorted_candidates = np.argsort(position)[::-1]
        selected: List[int] = []

        for cand in sorted_candidates:
            # Check proximity against already selected
            conflict = any(self.cand_dist_matrix[cand, s] < self.min_separation_m for s in selected)
            if not conflict:
                selected.append(int(cand))
            if len(selected) == budget:
                break

        # Fallback if strict separation exhausted the candidate set
        if len(selected) < budget:
            for cand in sorted_candidates:
                if cand not in selected:
                    selected.append(int(cand))
                if len(selected) == budget:
                    break

        return selected[:budget]

    def optimize(
        self,
        budget_stops: int = 15,
        time_limit_sec: float = 30.0,
        stagnation_patience: int = 10,
        seed: Optional[int] = None
    ) -> Dict[str, Any]:
        """
        Runs the Discrete Particle Swarm Optimization loop.

        Args:
            budget_stops: Number of proposed facilities (K).
            time_limit_sec: Maximum runtime allowed.
            stagnation_patience: Early stopping patience.
            seed: Optional random seed override.

        Returns:
            Dictionary containing best solution metrics, candidate IDs, convergence history, and runtime.
        """
        start_time = time.time()
        active_seed = seed if seed is not None else self.seed
        rng = np.random.RandomState(active_seed)

        logger.info(
            f"Running Discrete PSO (particles={self.num_particles}, iterations={self.iterations}, "
            f"w=[{self.w_max:.2f}->{self.w_min:.2f}], c1={self.c1}, c2={self.c2}, K={budget_stops}, seed={active_seed})..."
        )

        # 1. Particle Initialization
        # Position X: continuous values in [0, 1] representing relative priority
        positions = rng.uniform(0.0, 1.0, size=(self.num_particles, self.num_candidates))
        # Velocity V: initial velocities in [-1, 1]
        velocities = rng.uniform(-1.0, 1.0, size=(self.num_particles, self.num_candidates))

        # Personal Bests
        p_best_positions = positions.copy()
        p_best_scores = np.zeros(self.num_particles)
        p_best_selections: List[List[int]] = []

        for i in range(self.num_particles):
            sel = self.decode_particle_to_selection(positions[i], budget_stops)
            score, _ = self.evaluator.evaluate(sel)
            p_best_scores[i] = score
            p_best_selections.append(sel)

        # Global Best
        g_best_idx = int(np.argmax(p_best_scores))
        g_best_position = positions[g_best_idx].copy()
        g_best_score = float(p_best_scores[g_best_idx])
        g_best_selection = list(p_best_selections[g_best_idx])

        convergence_history: List[float] = [round(g_best_score, 3)]
        mean_fitness_history: List[float] = [round(float(np.mean(p_best_scores)), 3)]

        stagnant_count = 0

        # 2. Main PSO Iteration Loop
        for it in range(1, self.iterations + 1):
            if time.time() - start_time > time_limit_sec:
                logger.info(f"PSO reached runtime limit of {time_limit_sec}s at iteration {it}.")
                break

            # Dynamic inertia weight linear damping
            w = self.w_max - ((self.w_max - self.w_min) * (it / self.iterations))

            r1 = rng.uniform(0.0, 1.0, size=(self.num_particles, self.num_candidates))
            r2 = rng.uniform(0.0, 1.0, size=(self.num_particles, self.num_candidates))

            # Velocity update: V = w*V + c1*r1*(P_best - X) + c2*r2*(G_best - X)
            cognitive = self.c1 * r1 * (p_best_positions - positions)
            social = self.c2 * r2 * (g_best_position - positions)
            velocities = (w * velocities) + cognitive + social

            # Velocity clamping to prevent explosive particle trajectories
            velocities = np.clip(velocities, -self.v_max, self.v_max)

            # Position update
            positions = positions + velocities

            # Evaluate each particle's decoded discrete selection
            improved = False
            for i in range(self.num_particles):
                current_selection = self.decode_particle_to_selection(positions[i], budget_stops)
                score, _ = self.evaluator.evaluate(current_selection)

                # Update personal best
                if score > p_best_scores[i]:
                    p_best_scores[i] = score
                    p_best_positions[i] = positions[i].copy()
                    p_best_selections[i] = current_selection

                    # Update global best
                    if score > g_best_score + 1e-4:
                        g_best_score = score
                        g_best_position = positions[i].copy()
                        g_best_selection = current_selection
                        improved = True

            if improved:
                stagnant_count = 0
            else:
                stagnant_count += 1

            convergence_history.append(round(g_best_score, 3))
            mean_fitness_history.append(round(float(np.mean(p_best_scores)), 3))

            if stagnant_count >= stagnation_patience:
                logger.info(f"PSO reached convergence stagnation at iteration {it}.")
                break

        elapsed = time.time() - start_time

        # Final detailed evaluation of global best
        final_fitness, metrics = self.evaluator.evaluate(g_best_selection)
        selected_ids = self.evaluator.candidates_metric.iloc[g_best_selection]["candidate_id"].tolist()

        metrics.update({
            "algorithm": "Particle Swarm Optimization (Discrete PSO)",
            "execution_time_sec": round(elapsed, 4),
            "iterations_completed": len(convergence_history) - 1,
            "swarm_size": self.num_particles,
            "w_range": [self.w_max, self.w_min],
            "c1": self.c1,
            "c2": self.c2,
            "random_seed": active_seed,
            "selected_indices": sorted(g_best_selection),
            "selected_stop_ids": selected_ids,
            "convergence_history": convergence_history,
            "mean_fitness_history": mean_fitness_history,
            "disclaimer": FITNESS_DISCLAIMER
        })
        logger.info(
            f"Discrete PSO completed in {elapsed:.3f}s. Best Fitness: {final_fitness:.2f}, "
            f"Pop Covered: {metrics['population_covered']:,} ({metrics['coverage_pct']}%)"
        )
        return metrics
