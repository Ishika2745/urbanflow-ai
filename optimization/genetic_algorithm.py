"""
UrbanFlow AI - Nature-Inspired Genetic Algorithm (GA) Optimizer
Modular implementation for Equity-Aware Multi-Objective Public Transit Facility Location.

Representation:
- A chromosome is a set/list of K integer indices corresponding to chosen candidate infrastructure locations.
- Guaranteed uniqueness (no duplicate stops) and hard spatial feasibility constraints (separation rules).

Operators:
1. Feasible Initial Population Generation
2. Multi-Objective Equity Fitness Evaluation
3. Tournament Selection
4. Set-Preserving Crossover with Proximity Repair
5. Spatial Mutation Operator
6. Elitism Preservation
7. Multi-Criteria Termination (Generations, Stagnation, Runtime Timeout)
8. Convergence Tracking & Multi-Seed Stability

DISCLAIMER:
Candidate stops evaluated are potential planning recommendations for feeder connectivity
improvements generated by the UrbanFlow AI optimization model. They are not approved bus stops
or operational BEST facilities.
"""

import time
import random
from typing import Dict, Any, List, Tuple, Optional, Set
import numpy as np

from optimization.fitness_function import MultiObjectiveFitnessEvaluator, FITNESS_DISCLAIMER
from utils.logger import logger


class GeneticAlgorithmOptimizer:
    """
    Nature-inspired Genetic Algorithm for equity-aware public transit stop placement.
    Operates on K-index chromosomes with hard spatial constraint repair.
    """

    DISCLAIMER = FITNESS_DISCLAIMER

    def __init__(
        self,
        evaluator: MultiObjectiveFitnessEvaluator,
        population_size: int = 40,
        generations: int = 35,
        crossover_prob: float = 0.80,
        mutation_prob: float = 0.15,
        tournament_size: int = 3,
        elitism_count: int = 2,
        min_separation_m: float = 300.0,
        random_seed: Optional[int] = 42
    ):
        self.evaluator = evaluator
        self.num_candidates = len(evaluator.candidates_metric)
        self.pop_size = max(10, population_size)
        self.generations = max(5, generations)
        self.cx_prob = crossover_prob
        self.mut_prob = mutation_prob
        self.tourn_size = tournament_size
        self.elitism_count = max(1, min(elitism_count, self.pop_size // 4))
        self.min_separation_m = min_separation_m
        self.seed = random_seed

        # Precompute candidate-to-candidate metric distance matrix for rapid spatial repair
        cand_geoms = self.evaluator.candidates_metric.geometry
        coords = np.column_stack([cand_geoms.x.values, cand_geoms.y.values])
        self.cand_dist_matrix = np.linalg.norm(coords[:, None, :] - coords[None, :, :], axis=-1)

    def _repair_chromosome(self, chromosome: List[int], budget: int, rng: random.Random) -> List[int]:
        """
        Repairs an individual to ensure:
        1. Exact cardinality (length == budget)
        2. Strict uniqueness (no duplicate candidates)
        3. Hard separation constraint (min_separation_m)
        """
        # Step 1: Remove duplicates while preserving order
        unique_indices = []
        seen: Set[int] = set()
        for idx in chromosome:
            if 0 <= idx < self.num_candidates and idx not in seen:
                seen.add(idx)
                unique_indices.append(idx)

        # Step 2: Spatial conflict filtering
        valid_indices: List[int] = []
        for idx in unique_indices:
            # Check distance to all currently accepted indices
            conflict = False
            for accepted_idx in valid_indices:
                if self.cand_dist_matrix[idx, accepted_idx] < self.min_separation_m:
                    conflict = True
                    break
            if not conflict:
                valid_indices.append(idx)
            if len(valid_indices) == budget:
                break

        # Step 3: If shortfall, greedily/randomly sample unselected non-conflicting candidates
        if len(valid_indices) < budget:
            all_cands = list(range(self.num_candidates))
            rng.shuffle(all_cands)
            for cand in all_cands:
                if cand in valid_indices:
                    continue
                # Check conflict with existing
                conflict = any(self.cand_dist_matrix[cand, v] < self.min_separation_m for v in valid_indices)
                if not conflict:
                    valid_indices.append(cand)
                    if len(valid_indices) == budget:
                        break

        # Step 4: Fallback if candidate pool is too densely packed to satisfy strict separation
        if len(valid_indices) < budget:
            remaining = [c for c in range(self.num_candidates) if c not in valid_indices]
            needed = budget - len(valid_indices)
            valid_indices.extend(remaining[:needed])

        return valid_indices[:budget]

    def _generate_individual(self, budget: int, rng: random.Random) -> List[int]:
        """Generates a random valid chromosome of K unique candidates satisfying separation rules."""
        raw_selection = rng.sample(range(self.num_candidates), min(budget * 2, self.num_candidates))
        return self._repair_chromosome(raw_selection, budget, rng)

    def _crossover(self, parent1: List[int], parent2: List[int], budget: int, rng: random.Random) -> Tuple[List[int], List[int]]:
        """
        Set-preserving crossover:
        Exchanges subsets between parents, maintaining diverse candidate genetic material,
        and repairs both offspring.
        """
        if rng.random() > self.cx_prob:
            return list(parent1), list(parent2)

        cut = rng.randint(1, budget - 1) if budget > 2 else 1
        child1_raw = parent1[:cut] + [idx for idx in parent2 if idx not in parent1[:cut]]
        child2_raw = parent2[:cut] + [idx for idx in parent1 if idx not in parent2[:cut]]

        child1 = self._repair_chromosome(child1_raw, budget, rng)
        child2 = self._repair_chromosome(child2_raw, budget, rng)
        return child1, child2

    def _mutate(self, chromosome: List[int], budget: int, rng: random.Random) -> List[int]:
        """
        Spatial mutation operator:
        Swaps one or more genes with unselected feasible candidate locations.
        """
        mutated = list(chromosome)
        for i in range(len(mutated)):
            if rng.random() < self.mut_prob:
                # Pick a random candidate not in mutated
                unselected = [c for c in range(self.num_candidates) if c not in mutated]
                if unselected:
                    mutated[i] = rng.choice(unselected)

        return self._repair_chromosome(mutated, budget, rng)

    def _tournament_selection(
        self, population: List[List[int]], fitnesses: List[float], rng: random.Random
    ) -> List[int]:
        """Selects the highest fitness individual from a randomly chosen tournament bracket."""
        contenders_indices = rng.sample(range(len(population)), min(self.tourn_size, len(population)))
        best_idx = max(contenders_indices, key=lambda idx: fitnesses[idx])
        return list(population[best_idx])

    def optimize(
        self,
        budget_stops: int = 15,
        time_limit_sec: float = 30.0,
        stagnation_patience: int = 12,
        seed: Optional[int] = None
    ) -> Dict[str, Any]:
        """
        Executes the Genetic Algorithm optimization cycle.

        Args:
            budget_stops: Number of proposed facilities (K).
            time_limit_sec: Maximum runtime allowed before graceful early exit.
            stagnation_patience: Max consecutive generations with no fitness improvement before stopping.
            seed: Optional random seed override for reproducibility.

        Returns:
            Dictionary containing best solution metrics, candidate IDs, convergence history, and runtime.
        """
        start_time = time.time()
        active_seed = seed if seed is not None else self.seed
        rng = random.Random(active_seed)
        np_rng = np.random.RandomState(active_seed)

        logger.info(
            f"Running Genetic Algorithm (pop={self.pop_size}, gen={self.generations}, "
            f"cx_prob={self.cx_prob}, mut_prob={self.mut_prob}, K={budget_stops}, seed={active_seed})..."
        )

        # 1. Initialize Population
        population: List[List[int]] = [
            self._generate_individual(budget_stops, rng) for _ in range(self.pop_size)
        ]

        fitnesses: List[float] = []
        for ind in population:
            fit, _ = self.evaluator.evaluate(ind)
            fitnesses.append(fit)

        best_idx = int(np.argmax(fitnesses))
        best_chromosome = list(population[best_idx])
        best_fitness = float(fitnesses[best_idx])

        convergence_history: List[float] = [round(best_fitness, 3)]
        mean_fitness_history: List[float] = [round(float(np.mean(fitnesses)), 3)]

        stagnant_count = 0

        # 2. Evolutionary Loop
        for gen in range(1, self.generations + 1):
            if time.time() - start_time > time_limit_sec:
                logger.info(f"GA reached runtime limit of {time_limit_sec}s at generation {gen}.")
                break

            # Elitism: retain top E individuals
            elite_order = np.argsort(fitnesses)[::-1]
            elites = [list(population[i]) for i in elite_order[:self.elitism_count]]
            elite_fits = [fitnesses[i] for i in elite_order[:self.elitism_count]]

            # Reproduction pool
            new_population: List[List[int]] = list(elites)

            while len(new_population) < self.pop_size:
                p1 = self._tournament_selection(population, fitnesses, rng)
                p2 = self._tournament_selection(population, fitnesses, rng)

                c1, c2 = self._crossover(p1, p2, budget_stops, rng)
                c1 = self._mutate(c1, budget_stops, rng)
                c2 = self._mutate(c2, budget_stops, rng)

                new_population.append(c1)
                if len(new_population) < self.pop_size:
                    new_population.append(c2)

            population = new_population

            # Evaluate new population
            fitnesses = []
            for i, ind in enumerate(population):
                if i < self.elitism_count:
                    fitnesses.append(elite_fits[i])
                else:
                    fit, _ = self.evaluator.evaluate(ind)
                    fitnesses.append(fit)

            # Check for improvement
            current_best_idx = int(np.argmax(fitnesses))
            current_best_fit = float(fitnesses[current_best_idx])

            if current_best_fit > best_fitness + 1e-4:
                best_fitness = current_best_fit
                best_chromosome = list(population[current_best_idx])
                stagnant_count = 0
            else:
                stagnant_count += 1

            convergence_history.append(round(best_fitness, 3))
            mean_fitness_history.append(round(float(np.mean(fitnesses)), 3))

            # Early stopping check
            if stagnant_count >= stagnation_patience:
                logger.info(f"GA terminated early due to convergence plateau at generation {gen}.")
                break

        elapsed = time.time() - start_time

        # Final detailed evaluation of global best
        final_fitness, metrics = self.evaluator.evaluate(best_chromosome)
        selected_ids = self.evaluator.candidates_metric.iloc[best_chromosome]["candidate_id"].tolist()

        metrics.update({
            "algorithm": "Genetic Algorithm (Equity-GA)",
            "execution_time_sec": round(elapsed, 4),
            "generations_completed": len(convergence_history) - 1,
            "population_size": self.pop_size,
            "crossover_prob": self.cx_prob,
            "mutation_prob": self.mut_prob,
            "random_seed": active_seed,
            "selected_indices": sorted(best_chromosome),
            "selected_stop_ids": selected_ids,
            "convergence_history": convergence_history,
            "mean_fitness_history": mean_fitness_history,
            "disclaimer": FITNESS_DISCLAIMER
        })
        logger.info(
            f"Equity-GA completed in {elapsed:.3f}s. Best Fitness: {final_fitness:.2f}, "
            f"Pop Covered: {metrics['population_covered']:,} ({metrics['coverage_pct']}%)"
        )
        return metrics
