"""
UrbanFlow AI - P-Median Location Optimizer
Minimizes population-weighted travel distance to the nearest transit facility via Google OR-Tools (with PuLP fallback).

Implements Part B & Part C:
    Minimize sum_i sum_j (pop_i * d_{ij} * z_{ij})
    subject to:
        sum_j z_{ij} == 1                (each demand unit assigned to exactly 1 facility)
        z_{ij} <= x_j                    (can only assign to open facility)
        sum_j x_j <= K                   (maximum new facilities)
        x_j in {0, 1}, z_{ij} >= 0

DISCLAIMER:
Candidate stops evaluated are potential planning recommendations for feeder connectivity
improvements generated by the UrbanFlow AI optimization model. They are not approved bus stops
or operational BEST facilities.
"""

import time
from typing import Dict, Any, List, Optional
import numpy as np
from ortools.linear_solver import pywraplp
import pulp

from optimization.fitness_function import MultiObjectiveFitnessEvaluator, FITNESS_DISCLAIMER
from utils.logger import logger


class PMedianOptimizer:
    """Exact MILP solver for the classic P-Median problem using Google OR-Tools."""

    DISCLAIMER = FITNESS_DISCLAIMER

    def __init__(self, evaluator: MultiObjectiveFitnessEvaluator):
        self.evaluator = evaluator
        self.dist_matrix = evaluator.dist_matrix # (I x J) in meters
        self.populations = evaluator.populations
        self.num_demand_units = len(self.populations)
        self.num_candidates = len(evaluator.candidates_metric)

    def optimize(
        self,
        budget_stops: int = 15,
        max_budget_lakhs: Optional[float] = None,
        time_limit_sec: int = 30
    ) -> Dict[str, Any]:
        """
        Solves P-Median MILP minimizing total passenger walking distance.
        """
        start_time = time.time()
        logger.info(
            f"Formulating P-Median MILP (demand units: {self.num_demand_units}, "
            f"candidates: {self.num_candidates}, p: {budget_stops})..."
        )

        solver = pywraplp.Solver.CreateSolver("SCIP")
        if not solver:
            solver = pywraplp.Solver.CreateSolver("CBC")

        if solver:
            return self._solve_ortools(
                solver=solver,
                budget_stops=budget_stops,
                max_budget_lakhs=max_budget_lakhs,
                time_limit_sec=time_limit_sec,
                start_time=start_time
            )
        else:
            return self._solve_pulp(
                budget_stops=budget_stops,
                max_budget_lakhs=max_budget_lakhs,
                time_limit_sec=time_limit_sec,
                start_time=start_time
            )

    def _solve_ortools(
        self,
        solver: Any,
        budget_stops: int,
        max_budget_lakhs: Optional[float],
        time_limit_sec: int,
        start_time: float
    ) -> Dict[str, Any]:
        """Solves P-Median using Google OR-Tools."""
        solver.SetTimeLimit(time_limit_sec * 1000)

        # Decision variables: x_j (facility j opened), z_ij (demand unit i served by j)
        x = [solver.BoolVar(f"open_{j}") for j in range(self.num_candidates)]
        z = [
            [solver.NumVar(0.0, 1.0, f"assign_{i}_{j}") for j in range(self.num_candidates)]
            for i in range(self.num_demand_units)
        ]

        # Objective: minimize weighted distance (in km)
        objective = solver.Objective()
        for i in range(self.num_demand_units):
            pop = float(self.populations[i])
            for j in range(self.num_candidates):
                dist_km = float(self.dist_matrix[i, j]) / 1000.0
                objective.SetCoefficient(z[i][j], pop * dist_km)
        objective.SetMinimization()

        # Constraint 1: Facility limit
        budget_constraint = solver.Constraint(0, budget_stops)
        for j in range(self.num_candidates):
            budget_constraint.SetCoefficient(x[j], 1.0)

        # Constraint 2: Optional capital budget
        if max_budget_lakhs is not None and max_budget_lakhs > 0:
            cost_constraint = solver.Constraint(0, float(max_budget_lakhs))
            for j in range(self.num_candidates):
                cost_constraint.SetCoefficient(x[j], float(self.evaluator.costs[j]))

        # Constraint 3: Each demand unit must be assigned to exactly 1 facility
        for i in range(self.num_demand_units):
            assign_constraint = solver.Constraint(1.0, 1.0)
            for j in range(self.num_candidates):
                assign_constraint.SetCoefficient(z[i][j], 1.0)

        # Constraint 4: Linking constraint z_{ij} <= x_j  =>  z_{ij} - x_j <= 0
        for i in range(self.num_demand_units):
            for j in range(self.num_candidates):
                link_constraint = solver.Constraint(-solver.infinity(), 0.0)
                link_constraint.SetCoefficient(z[i][j], 1.0)
                link_constraint.SetCoefficient(x[j], -1.0)

        status = solver.Solve()
        elapsed = time.time() - start_time

        selected_mask = np.array([x[j].solution_value() > 0.5 for j in range(self.num_candidates)], dtype=bool)
        selected_indices = np.where(selected_mask)[0].tolist()

        final_fitness, metrics = self.evaluator.evaluate(selected_mask)
        selected_ids = self.evaluator.candidates_metric.iloc[selected_indices]["candidate_id"].tolist()
        status_str = "OPTIMAL" if status == pywraplp.Solver.OPTIMAL else "FEASIBLE"

        metrics.update({
            "algorithm": "P-Median (OR-Tools Exact MILP)",
            "execution_time_sec": round(elapsed, 4),
            "solver_status": status_str,
            "selected_indices": selected_indices,
            "selected_stop_ids": selected_ids,
            "convergence_history": [metrics["fitness"]],
            "disclaimer": FITNESS_DISCLAIMER
        })
        logger.info(
            f"P-Median solved in {elapsed:.3f}s with status '{status_str}'. "
            f"Avg Walk Dist: {metrics['avg_walking_distance_m']}m, Covered Pop: {metrics['population_covered']:,}"
        )
        return metrics

    def _solve_pulp(
        self,
        budget_stops: int,
        max_budget_lakhs: Optional[float],
        time_limit_sec: int,
        start_time: float
    ) -> Dict[str, Any]:
        """PuLP fallback solver for P-Median."""
        prob = pulp.LpProblem("PMedian_Transit", pulp.LpMinimize)

        x = [pulp.LpVariable(f"x_{j}", cat=pulp.LpBinary) for j in range(self.num_candidates)]
        z = [
            [pulp.LpVariable(f"z_{i}_{j}", lowBound=0, upBound=1, cat=pulp.LpContinuous) for j in range(self.num_candidates)]
            for i in range(self.num_demand_units)
        ]

        # Objective
        obj_terms = []
        for i in range(self.num_demand_units):
            pop = float(self.populations[i])
            for j in range(self.num_candidates):
                obj_terms.append(pop * (float(self.dist_matrix[i, j]) / 1000.0) * z[i][j])
        prob += pulp.lpSum(obj_terms)

        # Constraint: budget
        prob += pulp.lpSum(x) <= budget_stops

        # Assign each i to 1
        for i in range(self.num_demand_units):
            prob += pulp.lpSum([z[i][j] for j in range(self.num_candidates)]) == 1

        # Link z_ij <= x_j
        for i in range(self.num_demand_units):
            for j in range(self.num_candidates):
                prob += z[i][j] <= x[j]

        solver = pulp.PULP_CBC_CMD(timeLimit=time_limit_sec, msg=False)
        prob.solve(solver)
        elapsed = time.time() - start_time

        selected_mask = np.array([pulp.value(x[j]) > 0.5 for j in range(self.num_candidates)], dtype=bool)
        selected_indices = np.where(selected_mask)[0].tolist()

        final_fitness, metrics = self.evaluator.evaluate(selected_mask)
        selected_ids = self.evaluator.candidates_metric.iloc[selected_indices]["candidate_id"].tolist()

        metrics.update({
            "algorithm": "P-Median (PuLP Exact MILP)",
            "execution_time_sec": round(elapsed, 4),
            "solver_status": pulp.LpStatus[prob.status],
            "selected_indices": selected_indices,
            "selected_stop_ids": selected_ids,
            "convergence_history": [metrics["fitness"]],
            "disclaimer": FITNESS_DISCLAIMER
        })
        return metrics
