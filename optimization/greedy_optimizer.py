"""
UrbanFlow AI - Greedy Maximum Coverage Facility Location Optimizer
Implements Part B & Part C:
Deterministic baseline heuristic that iteratively selects candidate transit feeder stops
providing the maximal marginal population-weighted demand coverage and DTII reduction.

DISCLAIMER:
Candidate stops evaluated are potential planning recommendations for feeder connectivity
improvements generated by the UrbanFlow AI optimization model. They are not approved bus stops
or operational BEST facilities.
"""

import time
from typing import Dict, Any, List, Set, Optional
import numpy as np

from optimization.fitness_function import MultiObjectiveFitnessEvaluator, FITNESS_DISCLAIMER
from utils.logger import logger


class GreedyOptimizer:
    """Greedy Maximum Coverage forward-selection optimizer for transit stop placement."""

    DISCLAIMER = FITNESS_DISCLAIMER

    def __init__(self, evaluator: MultiObjectiveFitnessEvaluator):
        self.evaluator = evaluator
        self.coverage_matrix = evaluator.coverage_matrix # (I x J)
        self.dist_matrix = evaluator.dist_matrix         # (I x J)
        self.populations = evaluator.populations         # (I)
        self.num_candidates = len(evaluator.candidates_metric)
        self.num_demand_units = len(self.populations)

        # Precompute candidate coordinates in metric CRS for pairwise separation checks
        self.cand_coords = np.column_stack([
            evaluator.candidates_metric.geometry.x.values,
            evaluator.candidates_metric.geometry.y.values
        ])

    def optimize(
        self,
        budget_stops: int = 15,
        min_separation_m: float = 350.0,
        objective_mode: str = "population_weighted_demand"
    ) -> Dict[str, Any]:
        """
        Executes Greedy Maximum Coverage forward selection of K facilities.

        Objective:
            Maximize incremental population-weighted demand coverage while satisfying
            minimum spatial separation rules between selected stops.
        """
        start_time = time.time()
        logger.info(
            f"Running Greedy Maximum Coverage Optimizer: selecting K={budget_stops} "
            f"from {self.num_candidates} feasible candidates..."
        )

        selected_indices: List[int] = []
        available_indices: Set[int] = set(range(self.num_candidates))
        current_mask = np.zeros(self.num_candidates, dtype=bool)

        # Demand weights: w_i = pop_i * (1 + dtii_i) * demand_i
        w_dtii = self.evaluator.base_dtii
        w_dem = self.evaluator.base_demand
        demand_weights = self.populations * (1.0 + w_dtii) * (w_dem / 100.0)

        # Track currently covered demand units (including pre-covered)
        currently_covered = self.evaluator.pre_covered_flags.copy()
        convergence_history = []

        for step in range(min(budget_stops, self.num_candidates)):
            best_cand = None
            best_gain = -1.0

            for cand_idx in available_indices:
                # Check spatial separation rule with already selected stops
                if selected_indices and min_separation_m > 0:
                    cand_pt = self.cand_coords[cand_idx]
                    sel_pts = self.cand_coords[selected_indices]
                    dists_to_selected = np.hypot(sel_pts[:, 0] - cand_pt[0], sel_pts[:, 1] - cand_pt[1])
                    if np.min(dists_to_selected) < min_separation_m:
                        continue # Reject candidate violating minimum separation rule

                # Marginal gain: demand weight of previously uncovered units covered by candidate
                cand_coverage = self.coverage_matrix[:, cand_idx]
                newly_covered = cand_coverage & (~currently_covered)
                marginal_gain = float(np.sum(demand_weights[newly_covered]))

                # Tie-breaking with marginal fitness gain
                if marginal_gain > best_gain:
                    best_gain = marginal_gain
                    best_cand = cand_idx

            if best_cand is None:
                # If no candidate satisfies separation or provides positive gain, pick unconstrained best
                for cand_idx in available_indices:
                    trial_mask = current_mask.copy()
                    trial_mask[cand_idx] = True
                    fit, _ = self.evaluator.evaluate(trial_mask)
                    if fit > best_gain:
                        best_gain = fit
                        best_cand = cand_idx

            if best_cand is not None:
                selected_indices.append(best_cand)
                available_indices.remove(best_cand)
                current_mask[best_cand] = True
                currently_covered |= self.coverage_matrix[:, best_cand]
                
                # Record convergence metric
                step_fit, _ = self.evaluator.evaluate(current_mask)
                convergence_history.append(step_fit)

        elapsed = time.time() - start_time
        final_fitness, metrics = self.evaluator.evaluate(current_mask)

        selected_ids = self.evaluator.candidates_metric.iloc[selected_indices]["candidate_id"].tolist()
        metrics.update({
            "algorithm": "Greedy Maximum Coverage",
            "execution_time_sec": round(elapsed, 4),
            "selected_indices": selected_indices,
            "selected_stop_ids": selected_ids,
            "convergence_history": convergence_history,
            "disclaimer": FITNESS_DISCLAIMER
        })
        logger.info(
            f"Greedy optimization complete in {elapsed:.3f}s. "
            f"Stops: {len(selected_indices)}, Coverage: {metrics['population_covered']:,} ({metrics['coverage_pct']}%), "
            f"Additional Benefiting: {metrics['additional_population_benefiting']:,}"
        )
        return metrics
