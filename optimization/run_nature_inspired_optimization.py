def run_nature_inspired_optimization_pipeline(
    budget_stops: int = 15,
    service_radius_m: float = 800.0,
    min_separation_m: float = 300.0,
    alpha_coverage: float = 0.40,
    beta_equity: float = 0.30,
    gamma_dtii: float = 0.30,
    seeds: List[int] = [42, 101, 777, 2024, 9999]
) -> Dict[str, Any]:
    """
    Executes the complete Nature-Inspired Optimization & Benchmark suite.
    """
    logger.info("================================================================================")
    logger.info("  URBANFLOW AI - NATURE-INSPIRED EQUITY OPTIMIZATION ENGINE (DN-DS-01)")
    logger.info("================================================================================")

    # 1. Load Data
    wards_gdf, stops_gdf, candidates_gdf, _ = load_or_initialize_project_data()
    
    cand_path = Path("data/features/mumbai_feasible_candidates.parquet")
    if cand_path.exists():
        candidates_gdf = gpd.read_parquet(cand_path)
        logger.info(f"Loaded {len(candidates_gdf)} verified mapped infrastructure candidates.")
    else:
        logger.warning("Feasible candidates parquet not found, using default candidate stops.")

    # 2. Multi-Objective Fitness Evaluator
    evaluator = MultiObjectiveFitnessEvaluator(
        demand_wards_gdf=wards_gdf,
        candidate_stops_gdf=candidates_gdf,
        existing_stops_gdf=stops_gdf,
        service_radius_meters=service_radius_m,
        w_coverage=alpha_coverage,
        w_equity=beta_equity,
        w_dtii_reduction=gamma_dtii,
        min_separation_m=min_separation_m
    )

    suite = OptimizationBenchmarkSuite(evaluator)

    # 3. Complete 5-Way Comparison
    logger.info("\n--- STEP 1: Complete 5-Way Comparative Benchmark ---")
    df_5way, results_5way = suite.run_all(
        budget_stops=budget_stops,
        min_separation_m=min_separation_m,
        seed=42,
        return_raw=True
    )

    # 4. Multi-Seed Stability Benchmark
    logger.info(f"\n--- STEP 2: Multi-Seed Stability Benchmark across {len(seeds)} seeds ---")
    df_raw_stability, df_stability_stats = suite.run_stability_analysis(
        budget_stops=budget_stops,
        seeds=seeds
    )

    # 5. Persist Results
    out_dir = Path("data/processed")
    out_dir.mkdir(parents=True, exist_ok=True)
    
    df_5way.to_parquet(out_dir / "optimization_5way_benchmark.parquet", index=False)
    df_5way.to_csv(out_dir / "optimization_5way_benchmark.csv", index=False)
    
    df_raw_stability.to_csv(out_dir / "nature_inspired_stability_runs.csv", index=False)
    df_stability_stats.to_csv(out_dir / "nature_inspired_stability_stats.csv", index=False)

    # 6. Generate Folium Interactive Catchment Map
    map_path = _generate_nature_inspired_map(
        wards_gdf=wards_gdf,
        stops_gdf=stops_gdf,
        candidates_gdf=candidates_gdf,
        results_list=results_5way,
        service_radius_m=service_radius_m
    )

    # 7. Generate Executive Markdown Report
    report_path = _generate_markdown_report(
        df_5way=df_5way,
        df_stability_stats=df_stability_stats,
        results_list=results_5way,
        budget_stops=budget_stops,
        service_radius_m=service_radius_m,
        min_separation_m=min_separation_m,
        alpha=alpha_coverage,
        beta=beta_equity,
        gamma=gamma_dtii
    )

    logger.info("================================================================================")
    logger.info("  NATURE-INSPIRED EQUITY OPTIMIZATION PIPELINE COMPLETE")
    logger.info(f"  Benchmark Data:   {out_dir / 'optimization_5way_benchmark.csv'}")
    logger.info(f"  Stability Stats:  {out_dir / 'nature_inspired_stability_stats.csv'}")
    logger.info(f"  Interactive Map:  {map_path}")
    logger.info(f"  Executive Report: {report_path}")
    logger.info("================================================================================")

    return {
        "df_benchmark": df_5way,
        "df_stability_stats": df_stability_stats,
        "results": results_5way,
        "map_path": str(map_path),
        "report_path": str(report_path)
    }


def _generate_nature_inspired_map(
    wards_gdf: gpd.GeoDataFrame,
    stops_gdf: gpd.GeoDataFrame,
    candidates_gdf: gpd.GeoDataFrame,
    results_list: List[Dict[str, Any]],
    service_radius_m: float = 800.0
) -> Path:
    """Creates a multi-layered Folium map comparing GA, PSO, and Conventional stop placement."""
    wards_wgs = wards_gdf.to_crs(epsg=4326) if wards_gdf.crs != "EPSG:4326" else wards_gdf
    cand_wgs = candidates_gdf.to_crs(epsg=4326) if candidates_gdf.crs != "EPSG:4326" else candidates_gdf

    centroid = wards_wgs.geometry.union_all().centroid
    m = folium.Map(location=[centroid.y, centroid.x], zoom_start=11, tiles="OpenStreetMap")

    # Base Ward Polygons
    tooltip_fields = ["ward_id", "ward_name", "population"]
    tooltip_aliases = ["Ward:", "Name:", "Population:"]
    if "dtii" in wards_wgs.columns:
        tooltip_fields.append("dtii")
        tooltip_aliases.append("DTII Score:")
    elif "transit_desert_index" in wards_wgs.columns:
        tooltip_fields.append("transit_desert_index")
        tooltip_aliases.append("Transit Desert Index:")
    elif "accessibility_score" in wards_wgs.columns:
        tooltip_fields.append("accessibility_score")
        tooltip_aliases.append("Accessibility Score:")

    folium.GeoJson(
        wards_wgs,
        name="Mumbai Wards (Accessibility / Inequality)",
        style_function=lambda feature: {
            "fillColor": "#fee8c8" if feature["properties"].get("transit_desert_index", feature["properties"].get("dtii", 0.3)) < 0.35
            else "#fdbb84" if feature["properties"].get("transit_desert_index", feature["properties"].get("dtii", 0.3)) < 0.50
            else "#e34a33",
            "color": "#636363",
            "weight": 1.2,
            "fillOpacity": 0.35
        },
        tooltip=folium.GeoJsonTooltip(
            fields=tooltip_fields,
            aliases=tooltip_aliases,
            localize=True
        )
    ).add_to(m)

    algo_palette = {
        "Genetic Algorithm (Equity-GA)": "#E84A27",
        "Particle Swarm Optimization (Discrete PSO)": "#00529B",
        "Maximal Covering Location (MCLP MILP)": "#00B140",
        "Greedy Maximum Coverage": "#800080",
        "P-Median (Min Travel Distance MILP)": "#FF8C00"
    }

    # Add layers for each algorithm
    for res in results_list:
        algo_name = res.get("algorithm", "Algorithm")
        color = algo_palette.get(algo_name, "#333333")
        sel_ids = set(res.get("selected_stop_ids", []))
        
        layer = folium.FeatureGroup(name=f"{algo_name} (Stops: {len(sel_ids)})", show=("GA" in algo_name or "PSO" in algo_name))

        for _, row in cand_wgs.iterrows():
            if row["candidate_id"] in sel_ids:
                geom = row.geometry
                # Marker
                folium.CircleMarker(
                    location=[geom.y, geom.x],
                    radius=6,
                    color=color,
                    fill=True,
                    fill_color=color,
                    fill_opacity=0.9,
                    popup=folium.Popup(
                        f"<b>{algo_name}</b><br>"
                        f"<b>ID:</b> {row['candidate_id']}<br>"
                        f"<b>Location:</b> {row.get('candidate_name', 'Feeder Candidate')}<br>"
                        f"<b>Ward:</b> {row.get('ward_id')}<br>"
                        f"<b>Estimated Cost:</b> ₹{row.get('estimated_cost_lakhs', 25.0)} Lakhs<br>"
                        f"<i>Potential feeder improvement (UrbanFlow AI)</i>",
                        max_width=280
                    )
                ).add_to(layer)

                # Catchment buffer
                folium.Circle(
                    location=[geom.y, geom.x],
                    radius=service_radius_m,
                    color=color,
                    weight=1,
                    fill=True,
                    fill_color=color,
                    fill_opacity=0.08
                ).add_to(layer)

        layer.add_to(m)

    folium.LayerControl(collapsed=False).add_to(m)

    out_file = Path("reports/maps/nature_inspired_optimization_map.html")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    m.save(str(out_file))
    return out_file


