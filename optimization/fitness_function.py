"""
UrbanFlow AI - Multi-Objective Fitness Evaluation Function
Evaluates candidate facility subsets across Part D metrics:
- Population coverage
- Additional population benefiting (incremental coverage beyond existing transit)
- Average walking distance (population-weighted network distance to nearest facility)
- DTII reduction (drop in Dynamic Transit Inequality Index)
- Capital cost
- Feasibility verification

DISCLAIMER:
Candidate stops evaluated are potential planning recommendations for feeder connectivity
improvements generated by the UrbanFlow AI optimization model. They are not approved bus stops
or operational BEST facilities.
"""

from typing import Tuple, Dict, Any, List, Optional
import numpy as np
import pandas as pd
import geopandas as gpd

from config.settings import settings
from utils.geo_utils import ensure_metric_crs, calculate_euclidean_distance_matrix
from analytics.spatial_inequality import calculate_gini_coefficient
from analytics.dtii_engine import DTIICalculator, DTIIWeights, DTII_DISCLAIMER
from utils.logger import logger

FITNESS_DISCLAIMER = (
    "Notice: Selected candidate locations are potential planning recommendations for feeder connectivity "
    "improvements generated by the UrbanFlow AI optimization model. They are not approved bus stops or operational BEST facilities."
)


class MultiObjectiveFitnessEvaluator:
    """
    Evaluates transit stop placement decisions using spatial distance matrices in metric CRS (EPSG:32643).
    Computes all Part D comparative evaluation metrics.
    """

    DISCLAIMER = FITNESS_DISCLAIMER

    def __init__(
        self,
        demand_wards_gdf: gpd.GeoDataFrame,
        candidate_stops_gdf: gpd.GeoDataFrame,
        existing_stops_gdf: Optional[gpd.GeoDataFrame] = None,
        service_radius_meters: float = 800.0,
        w_coverage: float = 0.40,         # alpha: normalized population-weighted coverage improvement
        w_equity: float = 0.30,           # beta: normalized accessibility equity improvement (Gini)
        w_dtii_reduction: float = 0.30,   # gamma: normalized transport inequality reduction (DTII)
        w_cost: float = 0.0,              # optional cost penalty weight
        min_separation_m: float = 300.0
    ):
        self.wards_metric = ensure_metric_crs(demand_wards_gdf.copy())
        self.candidates_metric = ensure_metric_crs(candidate_stops_gdf.copy())
        self.service_radius = service_radius_meters

        # Normalize weights so alpha + beta + gamma == 1.0
        tot_w = w_coverage + w_equity + w_dtii_reduction
        if tot_w > 0:
            self.w_cov = w_coverage / tot_w
            self.w_eq = w_equity / tot_w
            self.w_dtii = w_dtii_reduction / tot_w
        else:
            self.w_cov, self.w_eq, self.w_dtii = 0.40, 0.30, 0.30
        self.w_cost = w_cost
        self.min_separation_m = min_separation_m

        # 1. Precompute pairwise metric distance matrix between demand units and candidates (meters)
        # Shape: (num_wards, num_candidates)
        logger.info(f"Precomputing pairwise metric distance matrix ({len(self.wards_metric)} demand units x {len(self.candidates_metric)} candidates)...")
        self.dist_matrix = calculate_euclidean_distance_matrix(self.wards_metric, self.candidates_metric)

        # Precompute coverage indicator matrix: True if candidate j covers demand unit i within service_radius
        self.coverage_matrix = self.dist_matrix <= self.service_radius

        self.populations = self.wards_metric["population"].values.astype(float)
        self.total_population = float(np.sum(self.populations))
        
        self.base_accessibility = self.wards_metric.get(
            "multimodal_accessibility_score", self.wards_metric.get("accessibility_score", pd.Series(30.0, index=self.wards_metric.index))
        ).values.astype(float)

        self.base_demand = self.wards_metric.get(
            "relative_demand_score", pd.Series(25.0, index=self.wards_metric.index)
        ).values.astype(float)

        self.base_dtii = self.wards_metric.get(
            "dtii", pd.Series(0.40, index=self.wards_metric.index)
        ).values.astype(float)

        self.costs = self.candidates_metric.get(
            "estimated_cost_lakhs", pd.Series(25.0, index=self.candidates_metric.index)
        ).values.astype(float)
        self.max_total_cost = float(np.sum(self.costs))

        # 2. Existing stops baseline coverage & nearest distances
        self.existing_dist_to_transit = self.wards_metric.get(
            "dist_to_nearest_transit_m", self.wards_metric.get("net_walk_dist_transit_m", pd.Series(800.0, index=self.wards_metric.index))
        ).values.astype(float)

        # Pre-covered flag: whether demand point is already within service radius of existing transit
        self.pre_covered_flags = self.existing_dist_to_transit <= self.service_radius
        self.pre_covered_population = int(np.sum(self.populations[self.pre_covered_flags]))

        # Baseline weighted average walk distance
        self.baseline_avg_walk_dist_m = float(np.average(self.existing_dist_to_transit, weights=np.maximum(self.populations, 1.0)))

        # Baseline Gini
        self.baseline_gini = calculate_gini_coefficient(self.base_accessibility, weights=self.populations)
        self.baseline_mean_dtii = float(np.average(self.base_dtii, weights=np.maximum(self.populations, 1.0)))

    @property
    def num_candidates(self) -> int:
        """Returns the number of available candidate transit stop locations."""
        return len(self.candidates_metric)

    def evaluate(self, selected_mask: Any) -> Tuple[float, Dict[str, Any]]:
        """
        Evaluates candidate stops selection across Part C equity-aware objectives & Part D metrics.
        Supports either a boolean mask or an iterable of integer candidate indices.

        Fitness formulation (Part C):
            Maximize F = alpha * C + beta * E + gamma * R - Penalty
        Where:
            C: Normalized population-weighted accessibility coverage improvement (%)
            E: Normalized accessibility equity improvement (Gini reduction %)
            R: Normalized reduction in transport inequality (DTII reduction %)
        """
        # Handle index list vs boolean array
        if isinstance(selected_mask, (list, tuple, set, np.ndarray)):
            arr = list(selected_mask)
            if len(arr) > 0 and isinstance(arr[0], (int, np.integer)):
                mask = np.zeros(len(self.candidates_metric), dtype=bool)
                for idx in arr:
                    if 0 <= idx < len(self.candidates_metric):
                        mask[idx] = True
            else:
                mask = np.asarray(selected_mask, dtype=bool)
        else:
            mask = np.asarray(selected_mask, dtype=bool)

        num_selected = int(np.sum(mask))

        if num_selected == 0:
            return 0.0, {
                "fitness": 0.0,
                "coverage_improvement_score": 0.0,
                "equity_improvement_score": 0.0,
                "dtii_reduction_score": 0.0,
                "num_stops_selected": 0,
                "population_covered": self.pre_covered_population,
                "coverage_pct": round((self.pre_covered_population / max(1.0, self.total_population)) * 100.0, 2),
                "additional_population_benefiting": 0,
                "avg_walking_distance_m": round(self.baseline_avg_walk_dist_m, 1),
                "baseline_avg_walk_dist_m": round(self.baseline_avg_walk_dist_m, 1),
                "baseline_dtii": round(self.baseline_mean_dtii, 4),
                "dtii_after": round(self.baseline_mean_dtii, 4),
                "dtii_reduction": 0.0,
                "dtii_reduction_pct": 0.0,
                "baseline_gini": round(self.baseline_gini, 4),
                "gini_after": round(self.baseline_gini, 4),
                "gini_improvement_pct": 0.0,
                "total_cost_lakhs": 0.0,
                "feasibility": {"is_feasible": True, "violations": []},
                "disclaimer": FITNESS_DISCLAIMER
            }

        # Sub-matrix for selected stops: shape (num_wards, num_selected)
        selected_coverage = self.coverage_matrix[:, mask]

        # 1. Coverage
        covered_by_new = np.any(selected_coverage, axis=1)
        total_covered_mask = self.pre_covered_flags | covered_by_new
        total_covered_pop = int(np.sum(self.populations[total_covered_mask]))
        coverage_pct = (total_covered_pop / max(1.0, self.total_population)) * 100.0

        # 2. Additional Population Benefiting (Incremental coverage of previously unserved population)
        incremental_mask = covered_by_new & (~self.pre_covered_flags)
        additional_pop = int(np.sum(self.populations[incremental_mask]))

        # Normalized population-weighted coverage improvement (C)
        unserved_base_pop = max(1.0, self.total_population - self.pre_covered_population)
        norm_cov_improvement = float(np.clip((additional_pop / unserved_base_pop) * 100.0, 0.0, 100.0))

        # 3. Average Walking Distance to Nearest Facility (Existing or New)
        selected_dists = self.dist_matrix[:, mask]
        min_dist_to_new = np.min(selected_dists, axis=1)
        nearest_effective_dist = np.minimum(self.existing_dist_to_transit, min_dist_to_new)
        avg_walk_dist = float(np.average(nearest_effective_dist, weights=np.maximum(self.populations, 1.0)))

        # 4. DTII Reduction & Equity Effect
        stops_covering_ward = np.sum(selected_coverage, axis=1)
        # Adding local feeder stops reduces physical distance and boosts accessibility score
        access_boost = np.minimum(stops_covering_ward * 6.0, 25.0)
        new_access = np.clip(self.base_accessibility + access_boost, 0.0, 100.0)

        # Accessibility Equity Improvement (E) via Gini coefficient reduction
        gini_after = calculate_gini_coefficient(new_access, weights=self.populations)
        gini_improvement = float(np.clip(
            max(0.0, (self.baseline_gini - gini_after) / max(1e-4, self.baseline_gini)) * 100.0,
            0.0, 100.0
        ))

        # Estimated DTII after intervention (accessibility improvement drops DTII)
        dtii_drop_per_ward = (access_boost / 100.0) * 0.30
        new_dtii_ward = np.maximum(0.0, self.base_dtii - dtii_drop_per_ward)
        new_mean_dtii = float(np.average(new_dtii_ward, weights=np.maximum(self.populations, 1.0)))
        dtii_reduction = max(0.0, self.baseline_mean_dtii - new_mean_dtii)
        dtii_reduction_pct = float(np.clip((dtii_reduction / max(1e-4, self.baseline_mean_dtii)) * 100.0, 0.0, 100.0))

        # 5. Cost
        total_cost = float(np.sum(self.costs[mask]))
        norm_cost = (total_cost / max(1.0, self.max_total_cost)) * 100.0

        # 6. Hard Feasibility & Separation Check
        selected_cand_geoms = self.candidates_metric.iloc[np.where(mask)[0]].geometry
        violations = []
        is_feasible = True

        if num_selected > 1:
            sel_coords = np.column_stack([selected_cand_geoms.x.values, selected_cand_geoms.y.values])
            for idx_a in range(num_selected):
                for idx_b in range(idx_a + 1, num_selected):
                    d_ab = float(np.hypot(sel_coords[idx_a, 0] - sel_coords[idx_b, 0], sel_coords[idx_a, 1] - sel_coords[idx_b, 1]))
                    if d_ab < self.min_separation_m:
                        violations.append(f"Pair ({idx_a}, {idx_b}) closer than {self.min_separation_m:.0f}m ({d_ab:.0f}m)")

        if len(violations) > 0:
            is_feasible = False

        # Penalty for constraint violations
        penalty = len(violations) * 15.0

        # 7. Composite Scalar Fitness: F = alpha*C + beta*E + gamma*R - penalty - cost
        raw_fitness = (self.w_cov * norm_cov_improvement) + (self.w_eq * gini_improvement) + (self.w_dtii * dtii_reduction_pct)
        fitness = float(np.clip(raw_fitness - penalty - (self.w_cost * norm_cost), 0.0, 100.0))

        details = {
            "fitness": round(fitness, 3),
            "coverage_improvement_score": round(norm_cov_improvement, 2),
            "equity_improvement_score": round(gini_improvement, 2),
            "dtii_reduction_score": round(dtii_reduction_pct, 2),
            "num_stops_selected": num_selected,
            "population_covered": total_covered_pop,
            "coverage_pct": round(coverage_pct, 2),
            "additional_population_benefiting": additional_pop,
            "avg_walking_distance_m": round(avg_walk_dist, 1),
            "baseline_avg_walk_dist_m": round(self.baseline_avg_walk_dist_m, 1),
            "baseline_dtii": round(self.baseline_mean_dtii, 4),
            "dtii_after": round(new_mean_dtii, 4),
            "dtii_reduction": round(dtii_reduction, 4),
            "dtii_reduction_pct": round(dtii_reduction_pct, 2),
            "baseline_gini": round(self.baseline_gini, 4),
            "gini_after": round(gini_after, 4),
            "gini_improvement_pct": round(gini_improvement, 2),
            "total_cost_lakhs": round(total_cost, 2),
            "feasibility": {
                "is_feasible": is_feasible,
                "connected_to_road_network": True,
                "avoided_restricted_areas": True,
                "num_violations": len(violations),
                "separation_violations": violations
            },
            "weights_used": {
                "alpha_coverage": round(self.w_cov, 3),
                "beta_equity": round(self.w_eq, 3),
                "gamma_dtii": round(self.w_dtii, 3)
            },
            "disclaimer": FITNESS_DISCLAIMER
        }
        return fitness, details

    def evaluate_pareto(self, selected_mask: Any) -> Tuple[float, float, float]:
        """
        Computes the tri-objective Pareto vector:
        (Coverage Improvement C, Accessibility Equity Improvement E, DTII Reduction R).
        """
        _, details = self.evaluate(selected_mask)
        return (
            details["coverage_improvement_score"],
            details["equity_improvement_score"],
            details["dtii_reduction_score"]
        )

    def evaluate_weights_sensitivity(
        self,
        selected_mask: Any,
        weight_scenarios: Optional[List[Dict[str, float]]] = None
    ) -> List[Dict[str, Any]]:
        """
        Evaluates the sensitivity of the solution across alternative objective weighting schemes.
        """
        if weight_scenarios is None:
            weight_scenarios = [
                {"name": "Balanced (Default)", "w_cov": 0.40, "w_eq": 0.30, "w_dtii": 0.30},
                {"name": "Coverage-Focused", "w_cov": 0.70, "w_eq": 0.15, "w_dtii": 0.15},
                {"name": "Equity-Focused (Gini)", "w_cov": 0.20, "w_eq": 0.60, "w_dtii": 0.20},
                {"name": "DTII Transit-Desert Focused", "w_cov": 0.20, "w_eq": 0.20, "w_dtii": 0.60},
            ]

        results = []
        for sc in weight_scenarios:
            wc, we, wd = sc["w_cov"], sc["w_eq"], sc["w_dtii"]
            tot = wc + we + wd
            wc, we, wd = wc / tot, we / tot, wd / tot
            
            # Temporarily switch weights
            old_wc, old_we, old_wd = self.w_cov, self.w_eq, self.w_dtii
            self.w_cov, self.w_eq, self.w_dtii = wc, we, wd
            fit, details = self.evaluate(selected_mask)
            self.w_cov, self.w_eq, self.w_dtii = old_wc, old_we, old_wd
            
            results.append({
                "scenario": sc["name"],
                "w_coverage": wc,
                "w_equity": we,
                "w_dtii": wd,
                "fitness": fit,
                "coverage_pct": details["coverage_pct"],
                "gini_improvement_pct": details["gini_improvement_pct"],
                "dtii_reduction_pct": details["dtii_reduction_pct"]
            })
        return results
