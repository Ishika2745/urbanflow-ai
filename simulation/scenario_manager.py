"""
UrbanFlow AI - Policy Scenario Manager
Handles persistent scenario storage, multi-scenario comparative benchmarking, and resetting (Part E).

DISCLAIMER:
All stored scenarios represent simulated policy projections generated by the UrbanFlow AI
decision-support model.
"""

from typing import Dict, Any, List, Optional
import uuid
import time
import pandas as pd
from utils.logger import logger


class ScenarioManager:
    """Manages saved simulation scenarios for interactive before-and-after policy comparison."""

    def __init__(self):
        self._scenarios: Dict[str, Dict[str, Any]] = {}

    def save_scenario(
        self,
        simulation_result: Dict[str, Any],
        algorithm_used: str = "Metaheuristic Optimizer",
        notes: str = ""
    ) -> str:
        """
        Saves a simulation output into the scenario registry.

        Returns:
            Unique scenario_id string.
        """
        scenario_id = f"SCEN_{uuid.uuid4().hex[:6].upper()}"
        timestamp = time.strftime("%Y-%m-%d %H:%M:%S")

        cov = simulation_result.get("coverage", {})
        walk = simulation_result.get("walking_distance", {})
        dtii = simulation_result.get("dtii", {})
        eq = simulation_result.get("equity", {})
        roi = simulation_result.get("socioeconomic_roi", {})

        record = {
            "scenario_id": scenario_id,
            "scenario_name": simulation_result.get("scenario_name", "Scenario"),
            "timestamp": timestamp,
            "algorithm": algorithm_used,
            "num_proposed_stops": simulation_result.get("num_proposed_stops", 0),
            "capital_cost_crores": simulation_result.get("capital_cost_crores", 0.0),

            # Core KPIs
            "coverage_pct": cov.get("simulated_coverage_pct", 0.0),
            "coverage_pct_gain": cov.get("coverage_pct_gain", 0.0),
            "incremental_pop_newly_served": cov.get("incremental_population_newly_served", 0),
            "total_benefiting_pop": cov.get("total_population_benefiting", 0),

            "simulated_avg_walk_dist_m": walk.get("simulated_avg_walk_dist_m", 0.0),
            "walk_dist_saved_m": walk.get("walk_dist_saved_m", 0.0),
            "walk_dist_saved_pct": walk.get("walk_dist_saved_pct", 0.0),

            "simulated_mean_dtii": dtii.get("simulated_mean_dtii", 0.0),
            "dtii_reduction_pct": dtii.get("dtii_reduction_pct", 0.0),
            "transit_deserts_alleviated": dtii.get("transit_deserts_alleviated", 0),

            "simulated_gini": eq.get("simulated_gini", 0.0),
            "gini_improvement_pct": eq.get("gini_improvement_pct", 0.0),

            "annual_hours_saved": roi.get("annual_hours_saved", 0),
            "annual_economic_benefit_crores": roi.get("annual_economic_benefit_crores", 0.0),
            "co2_metric_tons_avoided": roi.get("co2_metric_tons_avoided", 0.0),
            "payback_period_years": roi.get("payback_period_years", 0.0),
            "notes": notes,
            "full_result": simulation_result
        }

        self._scenarios[scenario_id] = record
        logger.info(f"Saved simulation scenario '{record['scenario_name']}' [ID: {scenario_id}].")
        return scenario_id

    def get_scenario(self, scenario_id: str) -> Optional[Dict[str, Any]]:
        """Retrieves a specific saved scenario by ID."""
        return self._scenarios.get(scenario_id)

    def get_all_scenarios(self) -> List[Dict[str, Any]]:
        """Returns all registered scenarios in chronological order."""
        return list(self._scenarios.values())

    def list_scenarios(self) -> pd.DataFrame:
        """Alias for get_comparison_dataframe()."""
        return self.get_comparison_dataframe()

    def get_comparison_dataframe(self) -> pd.DataFrame:
        """
        Produces a side-by-side comparative table of all saved scenarios.
        """
        if not self._scenarios:
            return pd.DataFrame()

        rows = []
        for s in self._scenarios.values():
            rows.append({
                "Scenario ID": s["scenario_id"],
                "Scenario Label": s["scenario_name"],
                "Algorithm": s["algorithm"],
                "Stops Added (K)": s["num_proposed_stops"],
                "Coverage %": f"{s['coverage_pct']:.1f}% (+{s['coverage_pct_gain']:.1f}%)",
                "Newly Served Pop": f"{s['incremental_pop_newly_served']:,}",
                "Total Benefiting Pop": f"{s['total_benefiting_pop']:,}",
                "Avg Walk Dist (m)": f"{s['simulated_avg_walk_dist_m']:.0f}m (-{s['walk_dist_saved_m']:.0f}m)",
                "DTII Reduction %": f"{s['dtii_reduction_pct']:.2f}%",
                "Deserts Resolved": s["transit_deserts_alleviated"],
                "Gini Improvement %": f"{s['gini_improvement_pct']:.2f}%",
                "CapEx (₹ Cr)": f"₹{s['capital_cost_crores']:.2f} Cr",
                "Payback (Yrs)": f"{s['payback_period_years']:.1f} yrs"
            })
        return pd.DataFrame(rows)

    def delete_scenario(self, scenario_id: str) -> bool:
        """Deletes a saved scenario."""
        if scenario_id in self._scenarios:
            del self._scenarios[scenario_id]
            return True
        return False

    def reset_all(self) -> None:
        """Resets the scenario repository."""
        self._scenarios.clear()
        logger.info("Cleared all saved simulation scenarios.")

