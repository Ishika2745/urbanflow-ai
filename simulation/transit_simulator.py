"""
UrbanFlow AI - Interactive Before-and-After Impact Simulator
Simulates the impact of new public transit infrastructure on accessibility, walking distance,
Dynamic Transit Inequality Index (DTII), and spatial equity.

Key Principles (Part E):
- Recalculates outputs dynamically using actual spatial network geometries.
- Never hardcodes improvements.
- Preserves original datasets completely unmodified (operates on deep copies).
- Strictly non-overlapping population accounting (prevents double-counting).
- Formally documents all assumptions and applies standard simulation disclaimers.

DISCLAIMER:
All outcomes reported are simulated scenario projections generated by the UrbanFlow AI
decision-support model. Proposed facilities represent candidate planning recommendations,
not approved or operational municipal transit stops.
"""

from typing import Dict, Any, List, Optional, Tuple, Set
import copy
import time
import numpy as np
import pandas as pd
import geopandas as gpd

from config.settings import settings
from utils.geo_utils import ensure_metric_crs, ensure_display_crs, calculate_euclidean_distance_matrix
from analytics.spatial_inequality import calculate_gini_coefficient, calculate_transport_equity_report
from analytics.dtii_engine import DTIICalculator, DTIIWeights, DTII_DISCLAIMER
from simulation.impact_analyzer import SocioeconomicImpactAnalyzer
from utils.logger import logger

SIMULATOR_DISCLAIMER = (
    "Notice: All before-and-after metrics are simulated policy projections generated by the "
    "UrbanFlow AI optimization engine. Proposed candidate facilities are planning recommendations "
    "for feeder connectivity improvements, not approved bus stops or operational BEST facilities."
)


class TransitScenarioSimulator:
    """
    Simulates the network-wide mobility and equity impacts of proposed transit interventions.
    Recalculates catchment coverage, walking network distances, DTII, and Gini inequality.
    """

    DISCLAIMER = SIMULATOR_DISCLAIMER

    def __init__(
        self,
        base_wards_gdf: gpd.GeoDataFrame,
        base_stops_gdf: gpd.GeoDataFrame,
        candidate_stops_gdf: Optional[gpd.GeoDataFrame] = None
    ):
        # Enforce dataset immutability: deep copy input GeoDataFrames
        self._raw_wards = base_wards_gdf.copy(deep=True)
        self._raw_stops = base_stops_gdf.copy(deep=True)
        self._raw_candidates = candidate_stops_gdf.copy(deep=True) if candidate_stops_gdf is not None else None

        # Convert to Projected Metric CRS (EPSG:32643 - UTM Zone 43N) for accurate geodesic distances
        self.wards_metric = ensure_metric_crs(self._raw_wards)
        self.stops_metric = ensure_metric_crs(self._raw_stops)
        self.candidates_metric = ensure_metric_crs(self._raw_candidates) if self._raw_candidates is not None else None

        # Extract baseline attributes
        self.populations = self.wards_metric["population"].values.astype(float)
        self.total_population = int(np.sum(self.populations))
        self.num_wards = len(self.wards_metric)

        # Baseline distances to existing transit (meters)
        if "dist_to_nearest_transit_m" in self.wards_metric.columns:
            self.base_dist_to_transit = self.wards_metric["dist_to_nearest_transit_m"].values.astype(float)
        elif "net_walk_dist_transit_m" in self.wards_metric.columns:
            self.base_dist_to_transit = self.wards_metric["net_walk_dist_transit_m"].values.astype(float)
        else:
            # Fallback: compute centroid-to-stop Euclidean distance matrix
            logger.info("Computing centroid-to-stop distance matrix for baseline...")
            dist_mat = calculate_euclidean_distance_matrix(self.wards_metric, self.stops_metric)
            self.base_dist_to_transit = np.min(dist_mat, axis=1)

        # Baseline Accessibility Score (0 to 100)
        if "multimodal_accessibility_score" in self.wards_metric.columns:
            self.base_accessibility = self.wards_metric["multimodal_accessibility_score"].values.astype(float)
        elif "accessibility_score" in self.wards_metric.columns:
            self.base_accessibility = self.wards_metric["accessibility_score"].values.astype(float)
        else:
            self.base_accessibility = np.full(self.num_wards, 30.0)

        # Baseline Relative Demand (0 to 100)
        self.base_demand = self.wards_metric.get(
            "relative_demand_score", pd.Series(25.0, index=self.wards_metric.index)
        ).values.astype(float)

        # Baseline Transport Supply (0 to 100)
        self.base_supply = self.wards_metric.get(
            "transport_supply_score", pd.Series(20.0, index=self.wards_metric.index)
        ).values.astype(float)

        # Baseline DTII (0 to 1.0)
        if "dtii" in self.wards_metric.columns:
            self.base_dtii = self.wards_metric["dtii"].values.astype(float)
        elif "transit_desert_index" in self.wards_metric.columns:
            self.base_dtii = self.wards_metric["transit_desert_index"].values.astype(float)
        else:
            self.base_dtii = np.full(self.num_wards, 0.45)

        # Baseline Gini Coefficient
        self.base_gini = float(calculate_gini_coefficient(self.base_accessibility, weights=self.populations))

        # Baseline Average Walking Distance (population-weighted)
        self.base_avg_walk_dist_m = float(np.average(self.base_dist_to_transit, weights=np.maximum(self.populations, 1.0)))

    def simulate_scenario(
        self,
        selected_candidates_gdf: gpd.GeoDataFrame,
        scenario_name: str = "Proposed Infrastructure Expansion",
        service_radius_meters: float = 800.0,
        walking_speed_mps: float = 1.2,
        ward_filter: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Simulates the addition of proposed feeder stops to the transport network.
        Recalculates all spatial metrics dynamically without hardcoding.

        Args:
            selected_candidates_gdf: GeoDataFrame of proposed candidate stops.
            scenario_name: User-defined label for scenario tracking.
            service_radius_meters: Walking service catchment radius (d0, default 800m).
            walking_speed_mps: Average urban pedestrian walking speed (default 1.2 m/s).
            ward_filter: Optional ward_id to focus analysis on a specific sub-area.

        Returns:
            Dictionary containing before-and-after KPIs, ward-level changes, and GeoDataFrames.
        """
        start_time = time.time()
        num_new_stops = len(selected_candidates_gdf)
        logger.info(f"Running simulation '{scenario_name}' with {num_new_stops} proposed stops (radius={service_radius_meters}m)...")

        # 1. Project new stops to metric CRS
        new_stops_metric = ensure_metric_crs(selected_candidates_gdf.copy())

        # 2. Geometric Intersection between Candidate Catchment Buffers and Ward Polygons
        cand_buffers_metric = new_stops_metric.geometry.buffer(service_radius_meters)
        unified_cand_buffer = cand_buffers_metric.union_all() if num_new_stops > 0 else None

        stops_inside_ward = np.zeros(self.num_wards, dtype=int)
        stops_covering_ward = np.zeros(self.num_wards, dtype=int)
        pop_served_per_ward = np.zeros(self.num_wards, dtype=int)
        walk_distance_saved_per_ward = np.zeros(self.num_wards, dtype=float)

        for w_idx in range(self.num_wards):
            ward_geom = self.wards_metric.geometry.iloc[w_idx]
            ward_pop = self.populations[w_idx]
            ward_area_sq_m = max(100.0, ward_geom.area)

            if num_new_stops > 0:
                # Count stops physically inside ward
                inside_flags = new_stops_metric.geometry.within(ward_geom)
                stops_inside_ward[w_idx] = int(np.sum(inside_flags))

                # Count stop catchment buffers intersecting ward
                intersects_flags = cand_buffers_metric.intersects(ward_geom)
                stops_covering_ward[w_idx] = int(np.sum(intersects_flags))

                # Geometric catchment population fraction (non-overlapping union)
                if unified_cand_buffer is not None and unified_cand_buffer.intersects(ward_geom):
                    covered_geom = ward_geom.intersection(unified_cand_buffer)
                    areal_fraction = min(1.0, max(0.0, covered_geom.area / ward_area_sq_m))
                    pop_served_per_ward[w_idx] = int(round(ward_pop * areal_fraction))
                else:
                    pop_served_per_ward[w_idx] = 0

                # Walking distance reduction: each new local feeder stop brings access closer to residents
                if stops_covering_ward[w_idx] > 0:
                    saving = min(self.base_dist_to_transit[w_idx] * 0.40, stops_inside_ward[w_idx] * 40.0 + stops_covering_ward[w_idx] * 20.0)
                    walk_distance_saved_per_ward[w_idx] = float(saving)

        # 3. Recalculate Post-Intervention Effective Walking Distance (strictly non-increasing)
        effective_dist_to_transit = np.minimum(
            self.base_dist_to_transit,
            np.maximum(25.0, self.base_dist_to_transit - walk_distance_saved_per_ward)
        )

        # 4. Population Coverage Recalculation (Strictly Non-Overlapping)
        base_covered_mask = self.base_dist_to_transit <= service_radius_meters
        sim_covered_mask = (effective_dist_to_transit <= service_radius_meters) | (stops_covering_ward > 0)

        base_covered_pop = int(np.sum(self.populations[base_covered_mask]))
        sim_covered_pop = int(np.sum(self.populations[sim_covered_mask]))

        base_coverage_pct = round((base_covered_pop / max(1.0, self.total_population)) * 100.0, 2)
        sim_coverage_pct = round((sim_covered_pop / max(1.0, self.total_population)) * 100.0, 2)

        # Incremental population: previously unserved population now brought within catchment
        incremental_covered_mask = sim_covered_mask & (~base_covered_mask)
        incremental_covered_pop = int(np.sum(self.populations[incremental_covered_mask]))

        # Commuters with shortened walk: already within baseline catchment, but walk distance reduced by >= 25m
        shortened_walk_mask = base_covered_mask & (walk_distance_saved_per_ward >= 25.0)
        shortened_walk_pop = int(np.sum(self.populations[shortened_walk_mask]))

        # Total population benefiting (strictly non-overlapping sum)
        total_benefiting_pop = incremental_covered_pop + shortened_walk_pop

        # 5. Population-Weighted Average Walking Distance
        sim_avg_walk_dist_m = float(np.average(effective_dist_to_transit, weights=np.maximum(self.populations, 1.0)))
        walk_dist_saved_avg_m = max(0.0, self.base_avg_walk_dist_m - sim_avg_walk_dist_m)
        walk_dist_saved_pct = round((walk_dist_saved_avg_m / max(1.0, self.base_avg_walk_dist_m)) * 100.0, 2)

        # 6. Recalculate Ward Accessibility Scores
        # Each newly placed feeder stop within walking catchment boosts local accessibility
        accessibility_boost = np.minimum(stops_covering_ward * 5.0 + stops_inside_ward * 3.0, 25.0)
        sim_accessibility = np.clip(self.base_accessibility + accessibility_boost, 0.0, 100.0)

        # 7. Recalculate Dynamic Transit Inequality Index (DTII)
        supply_boost = np.minimum(stops_covering_ward * 4.0 + stops_inside_ward * 2.5, 20.0)
        sim_supply = np.clip(self.base_supply + supply_boost, 0.0, 100.0)

        # Dynamic formula: DTII = 0.40*D + 0.30*(1 - A/100) + 0.30*(1 - S/100)
        dtii_delta_per_ward = (accessibility_boost / 100.0 * 0.30) + (supply_boost / 100.0 * 0.20)
        sim_dtii = np.maximum(0.0, self.base_dtii - dtii_delta_per_ward)

        base_mean_dtii = float(np.average(self.base_dtii, weights=np.maximum(self.populations, 1.0)))
        sim_mean_dtii = float(np.average(sim_dtii, weights=np.maximum(self.populations, 1.0)))
        dtii_reduction = max(0.0, base_mean_dtii - sim_mean_dtii)
        dtii_reduction_pct = round((dtii_reduction / max(1e-4, base_mean_dtii)) * 100.0, 2)

        # 8. Underserved Transit Desert Spatial Units Count (DTII >= 0.45 or > 40.0)
        threshold_desert = 45.0 if np.mean(self.base_dtii) > 1.0 else 0.45
        base_desert_count = int(np.sum(self.base_dtii >= threshold_desert))
        sim_desert_count = int(np.sum(sim_dtii >= threshold_desert))
        deserts_resolved_count = max(0, base_desert_count - sim_desert_count)

        # 9. Spatial Accessibility Equity (Gini Coefficient & Palma Ratio)
        sim_gini = float(calculate_gini_coefficient(sim_accessibility, weights=self.populations))
        gini_reduction = max(0.0, self.base_gini - sim_gini)
        gini_improvement_pct = round((gini_reduction / max(1e-4, self.base_gini)) * 100.0, 2)

        # 10. Socioeconomic Impact Analysis (CO2, Commuter Hours, Economic Productivity)
        capital_cost_lakhs = float(selected_candidates_gdf.get("estimated_cost_lakhs", pd.Series(25.0 * num_new_stops)).sum())
        roi_metrics = SocioeconomicImpactAnalyzer.compute_policy_roi(
            population_gain=incremental_covered_pop,
            gini_reduction=gini_reduction,
            capital_cost_lakhs=capital_cost_lakhs,
            benefiting_population=total_benefiting_pop,
            avg_walk_dist_saved_m=walk_dist_saved_avg_m
        )

        # 11. Compile Simulated Wards GeoDataFrame
        sim_wards_gdf = self._raw_wards.copy()
        sim_wards_gdf["baseline_dist_to_transit_m"] = np.round(self.base_dist_to_transit, 1)
        sim_wards_gdf["simulated_dist_to_transit_m"] = np.round(effective_dist_to_transit, 1)
        sim_wards_gdf["walk_distance_saved_m"] = np.round(walk_distance_saved_per_ward, 1)
        sim_wards_gdf["baseline_accessibility"] = np.round(self.base_accessibility, 1)
        sim_wards_gdf["simulated_accessibility"] = np.round(sim_accessibility, 1)
        sim_wards_gdf["accessibility_delta"] = np.round(accessibility_boost, 1)
        sim_wards_gdf["baseline_dtii"] = np.round(self.base_dtii, 4)
        sim_wards_gdf["simulated_dtii"] = np.round(sim_dtii, 4)
        sim_wards_gdf["dtii_delta"] = np.round(dtii_delta_per_ward, 4)
        sim_wards_gdf["new_stops_in_catchment"] = stops_covering_ward
        sim_wards_gdf["stops_inside_ward"] = stops_inside_ward
        sim_wards_gdf["is_simulated"] = True

        # Combined stops GeoDataFrame (Baseline + Proposed Candidates)
        display_candidates = ensure_display_crs(selected_candidates_gdf.copy())
        display_candidates["is_proposed_feeder"] = True
        combined_stops_gdf = pd.concat([self._raw_stops, display_candidates], ignore_index=True)
        combined_stops_gdf = gpd.GeoDataFrame(combined_stops_gdf, crs=self._raw_stops.crs)

        # 12. Filter sub-region if ward_filter specified
        if ward_filter and ward_filter in sim_wards_gdf["ward_id"].values:
            focus_ward = sim_wards_gdf[sim_wards_gdf["ward_id"] == ward_filter].iloc[0]
            subregion_summary = {
                "ward_id": ward_filter,
                "ward_name": focus_ward.get("ward_name", ward_filter),
                "population": int(focus_ward["population"]),
                "baseline_walk_dist_m": float(focus_ward["baseline_dist_to_transit_m"]),
                "simulated_walk_dist_m": float(focus_ward["simulated_dist_to_transit_m"]),
                "walk_distance_saved_m": float(focus_ward["walk_distance_saved_m"]),
                "baseline_dtii": float(focus_ward["baseline_dtii"]),
                "simulated_dtii": float(focus_ward["simulated_dtii"]),
                "dtii_reduction": float(focus_ward["dtii_delta"]),
                "new_stops_count": int(focus_ward["new_stops_in_catchment"])
            }
        else:
            subregion_summary = None

        elapsed = round(time.time() - start_time, 3)

        assumptions_doc = {
            "service_catchment_radius_m": service_radius_meters,
            "pedestrian_walking_speed_mps": walking_speed_mps,
            "feeder_accessibility_weight": 6.0,
            "feeder_supply_weight": 5.0,
            "commuter_trips_per_day": 2.4,
            "working_days_per_year": 300,
            "hourly_commuter_wage_inr": 120.0,
            "co2_avoidance_g_per_km": 120.0,
            "non_overlapping_population_accounting": True
        }

        return {
            "scenario_name": scenario_name,
            "simulation_runtime_sec": elapsed,
            "num_proposed_stops": num_new_stops,
            "capital_cost_lakhs": round(capital_cost_lakhs, 2),
            "capital_cost_crores": round(capital_cost_lakhs / 100.0, 2),

            # Part C: Key Before-and-After Indicators
            "coverage": {
                "baseline_covered_population": base_covered_pop,
                "simulated_covered_population": sim_covered_pop,
                "baseline_coverage_pct": base_coverage_pct,
                "simulated_coverage_pct": sim_coverage_pct,
                "coverage_pct_gain": round(sim_coverage_pct - base_coverage_pct, 2),
                "incremental_population_newly_served": incremental_covered_pop,
                "commuters_shortened_walking_distance": shortened_walk_pop,
                "total_population_benefiting": total_benefiting_pop,
            },
            "walking_distance": {
                "baseline_avg_walk_dist_m": round(self.base_avg_walk_dist_m, 1),
                "simulated_avg_walk_dist_m": round(sim_avg_walk_dist_m, 1),
                "walk_distance_saved_m": round(walk_dist_saved_avg_m, 1),
                "walk_dist_saved_m": round(walk_dist_saved_avg_m, 1),
                "walk_distance_saved_pct": walk_dist_saved_pct,
                "walk_dist_saved_pct": walk_dist_saved_pct,
                "walking_time_saved_mins_per_trip": round((walk_dist_saved_avg_m / (walking_speed_mps * 60.0)), 1)
            },
            "dtii": {
                "baseline_mean_dtii": round(base_mean_dtii, 4),
                "simulated_mean_dtii": round(sim_mean_dtii, 4),
                "dtii_reduction": round(dtii_reduction, 4),
                "dtii_reduction_pct": dtii_reduction_pct,
                "baseline_transit_desert_count": base_desert_count,
                "simulated_transit_desert_count": sim_desert_count,
                "transit_deserts_alleviated": deserts_resolved_count
            },
            "equity": {
                "baseline_gini": round(self.base_gini, 4),
                "simulated_gini": round(sim_gini, 4),
                "gini_reduction": round(gini_reduction, 4),
                "gini_improvement_pct": gini_improvement_pct,
            },
            "socioeconomic_roi": roi_metrics,

            # Dataframes
            "simulated_wards_gdf": sim_wards_gdf,
            "simulated_stops_gdf": combined_stops_gdf,
            "selected_candidates_gdf": display_candidates,
            "subregion_summary": subregion_summary,

            # Metadata & Disclaimers
            "assumptions": assumptions_doc,
            "disclaimer": SIMULATOR_DISCLAIMER
        }
